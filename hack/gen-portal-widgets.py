#!/usr/bin/env python3
"""Generate each blueprint's Marketplace tile, and with --check, fail when one is missing or stale.

Every blueprint with a compositiondefinition.yaml gets three files under its portal/ directory:

- card.<name>.yaml, the antd Card;
- restaction.<name>-card.yaml, which reads the CompositionDefinition's Ready condition and chart version;
- button.<name>-install.yaml, which opens the install form.

Inputs, and nothing else:

- the blueprint name, which is the directory name and gives the title;
- the CompositionDefinition's `krateo.io/icon` annotation, which gives the tile icon;
- the repository's GitHub topics, which give the tags.

The files were first written by a scratch script that was never committed, so no one could
regenerate them. powerdns and redis were added after it ran and got no tile, and nothing
noticed. This script is the generator, and --check is the gate that notices.

--check exits non-zero when a blueprint has no `krateo.io/icon`, when a tile file is missing,
differs from what this script renders, or belongs to no blueprint, or when it finds no
blueprints, because a gate that inspected nothing has said nothing.

Topics come from `gh api repos/<repo>/topics`, where <repo> is $GITHUB_REPOSITORY or --repo.
Changing the repository's topics makes --check fail until the tiles are regenerated. That is
intended: the tags are meant to follow the topics.
"""
import argparse
import json
import os
import subprocess
import sys

try:
    import yaml
except ImportError:
    sys.exit("ERROR: PyYAML is required")

NAMESPACE = "openstack-system"
HEADER = "# GENERATED by hack/gen-portal-widgets.py from ../compositiondefinition.yaml — do not edit by hand.\n"
ICON_ANNOTATION = "krateo.io/icon"
DEFAULT_REPO = "krateo-blueprints/krateo-openstack-blueprint"


def card(name, icon, tags):
    title = name.capitalize()
    tag_lines = "".join(f"      - {t}\n" for t in tags)
    return (
        HEADER
        + "apiVersion: widgets.templates.krateo.io/v1beta1\n"
        "kind: Card\n"
        "metadata:\n"
        f"  name: {name}\n"
        f"  namespace: {NAMESPACE}\n"
        "  labels:\n"
        "    krateo.io/portal-page: blueprints\n"
        "spec:\n"
        "  apiRef:\n"
        f"    name: {name}-card-data\n"
        f"    namespace: {NAMESPACE}\n"
        "  widgetData:\n"
        f"    title: {title}\n"
        f"    headerLeft: Provision the {title} blueprint.\n"
        f"    tooltip: {title} blueprint\n"
        "    icon:\n"
        f"      name: {icon}\n"
        "      color: grey\n"
        "    tags:\n"
        + tag_lines
        + "    extra: ''\n"
        "    items: []\n"
        "    footer:\n"
        f"      - resourceRefId: {name}-install\n"
        "  widgetDataTemplate:\n"
        "    - forPath: extra\n"
        "      expression: '${ \"Ready: \" + .ready + (if .version != \"—\" then \" · v\" + .version else \"\" end) }'\n"
        "    - forPath: icon\n"
        f"      expression: '${{ {{ name: \"{icon}\", color: (if .ready == \"True\" then \"green\" elif .ready == \"False\" then \"orange\" else \"grey\" end) }} }}'\n"
        "  resourcesRefs:\n"
        "    items:\n"
        f"      - id: {name}-install\n"
        "        apiVersion: widgets.templates.krateo.io/v1beta1\n"
        f"        name: {name}-install\n"
        f"        namespace: {NAMESPACE}\n"
        "        resource: buttons\n"
        "        verb: GET\n"
    )


def restaction(name):
    return (
        HEADER
        + "apiVersion: templates.krateo.io/v1\n"
        "kind: RESTAction\n"
        "metadata:\n"
        f"  name: {name}-card-data\n"
        f"  namespace: {NAMESPACE}\n"
        "  annotations:\n"
        "    krateo.io/verbose: 'true'\n"
        "spec:\n"
        "  api:\n"
        "    - name: cd\n"
        f"      path: /apis/core.krateo.io/v1alpha1/namespaces/{NAMESPACE}/compositiondefinitions/{name}\n"
        "      verb: GET\n"
        "      continueOnError: true\n"
        "      errorKey: cdError\n"
        "  filter: |\n"
        "    {\n"
        "      version: (.cd.spec.chart.version // \"—\"),\n"
        "      ready: (((.cd.status.conditions // []) | map(select(.type == \"Ready\"))[0].status) // \"Unknown\"),\n"
        "      ts: (.cd.metadata.creationTimestamp // \"\")\n"
        "    }\n"
    )


def button(name):
    return (
        HEADER
        + "apiVersion: widgets.templates.krateo.io/v1beta1\n"
        "kind: Button\n"
        "metadata:\n"
        f"  name: {name}-install\n"
        f"  namespace: {NAMESPACE}\n"
        "spec:\n"
        "  widgetData:\n"
        "    label: Install\n"
        "    type: primary\n"
        "    size: small\n"
        "    icon: fa-download\n"
        "    clickActionId: install\n"
        "    actions:\n"
        "      navigate:\n"
        "        - id: install\n"
        "          type: navigate\n"
        f"          path: /marketplace/{NAMESPACE}/{name}/new\n"
        "  resourcesRefs:\n"
        "    items: []\n"
    )


def topics(repo):
    try:
        out = subprocess.run(
            ["gh", "api", f"repos/{repo}/topics", "--jq", ".names"],
            check=True, capture_output=True, text=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit(f"ERROR: could not read the topics of {repo}: {getattr(e, 'stderr', '') or e}")
    names = json.loads(out)
    if not names:
        sys.exit(f"ERROR: {repo} has no topics, so every tile would have no tags")
    return sorted(names)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", nargs="?", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--check", action="store_true", help="write nothing; fail if any tile is missing or stale")
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", DEFAULT_REPO))
    args = ap.parse_args()

    bp_root = os.path.join(os.path.abspath(args.root), "blueprints")
    if not os.path.isdir(bp_root):
        sys.exit(f"ERROR: {bp_root} does not exist")
    tags = topics(args.repo)
    problems = []
    expected = {}

    names = sorted(
        n for n in os.listdir(bp_root)
        if os.path.isfile(os.path.join(bp_root, n, "compositiondefinition.yaml"))
    )
    if not names:
        sys.exit(f"ERROR: no blueprints with a compositiondefinition.yaml under {bp_root}")

    for name in names:
        with open(os.path.join(bp_root, name, "compositiondefinition.yaml")) as f:
            cd = yaml.safe_load(f)
        icon = ((cd.get("metadata") or {}).get("annotations") or {}).get(ICON_ANNOTATION)
        if not icon:
            problems.append(f"{name}: compositiondefinition.yaml has no metadata.annotations.{ICON_ANNOTATION}")
            continue
        portal = os.path.join(bp_root, name, "portal")
        expected[os.path.join(portal, f"card.{name}.yaml")] = card(name, icon, tags)
        expected[os.path.join(portal, f"restaction.{name}-card.yaml")] = restaction(name)
        expected[os.path.join(portal, f"button.{name}-install.yaml")] = button(name)

    for path, content in expected.items():
        rel = os.path.relpath(path, os.path.dirname(bp_root))
        current = open(path).read() if os.path.exists(path) else None
        if current == content:
            continue
        if args.check:
            problems.append(f"{rel}: {'missing' if current is None else 'differs from the generator'}")
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w") as f:
                f.write(content)
            print(f"wrote {rel}")

    for name in os.listdir(bp_root):
        portal = os.path.join(bp_root, name, "portal")
        if not os.path.isdir(portal):
            continue
        for fn in os.listdir(portal):
            path = os.path.join(portal, fn)
            if path not in expected and name in names:
                problems.append(f"{os.path.relpath(path, os.path.dirname(bp_root))}: not produced by the generator")
        if name not in names:
            problems.append(f"blueprints/{name}/portal: no compositiondefinition.yaml beside it")

    if problems:
        print("Marketplace tiles are missing or stale. Fix the annotation if one is named, then run "
              "`python3 hack/gen-portal-widgets.py` and commit the result:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        sys.exit(1)
    print(f"OK: {len(names)} blueprints, {len(expected)} tile files, tags {','.join(tags)}")


if __name__ == "__main__":
    main()
