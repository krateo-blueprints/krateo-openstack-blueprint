#!/usr/bin/env python3
"""Generate the per-cluster chart's inputs from the umbrella, so the two cannot disagree.

    python3 hack/gen-capabilities-chart.py [root]           write the three files
    python3 hack/gen-capabilities-chart.py [root] --check   exit 1 if any differs; write nothing

The per-cluster chart blueprints/openstack/capabilities renders the capability ClusterRoles and
guards that the umbrella rendered up to 0.3.46. During the handoff from a 0.3.46 install, the
umbrella re-renders the objects it still owns (templates/_capabilities.tpl explains why). So
the two charts must render the same objects from the same values. Copies of templates and
values drift silently: an edit to one copy renders fine and changes only one chart. So the
per-cluster chart has no hand-written copy. Three files are generated from the umbrella:

  templates/_capabilities.tpl   byte-for-byte copy of the umbrella's
  values.yaml                   the umbrella's `serviceContract:` block, verbatim with comments
  values.schema.json            the umbrella's `serviceContract` schema and the definitions it
                                references, so a deployer's serviceContract override is
                                validated identically by both charts. The top level is left
                                open, as the umbrella's is, so the SAME values file a deployer
                                uses for the Openstack spec can be passed to this chart unchanged.

hack/validate-capability-roles.py runs this with --check, so a hand edit to the generated files,
or an umbrella edit without regenerating, fails CI.

Requires: pyyaml.
"""
import difflib
import json
import re
import sys
from pathlib import Path

import yaml

TPL = "templates/_capabilities.tpl"


def serviceContract_block(values_text: str) -> str:
    """The `serviceContract:` top-level block of the umbrella values.yaml, as text.

    It ends at the first later line that starts in column 0 (a key or a comment), with trailing
    blank lines dropped. The comment banner above `contractEmitter:` belongs to that key.
    """
    lines = values_text.splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if l == "serviceContract:")
    except StopIteration:
        sys.exit("umbrella values.yaml has no top-level `serviceContract:` line")
    end = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i] and not lines[i][0].isspace():
            end = i
            break
    block = lines[start:end]
    while block and not block[-1].strip():
        block.pop()
    return "\n".join(block) + "\n"


def referenced_definitions(node, definitions, out):
    for ref in re.findall(r'"#/definitions/([A-Za-z0-9_]+)"', json.dumps(node)):
        if ref not in out:
            if ref not in definitions:
                sys.exit(f"umbrella schema references #/definitions/{ref}, which it does not define")
            out[ref] = definitions[ref]
            referenced_definitions(definitions[ref], definitions, out)
    return out


def generate(root: Path) -> dict:
    umbrella = root / "blueprints" / "openstack" / "chart"
    values_text = (umbrella / "values.yaml").read_text()
    umbrella_values = yaml.safe_load(values_text)
    block = serviceContract_block(values_text)

    # The text slice must mean exactly what the umbrella's parsed values mean, or the slice
    # rule above has cut the block in the wrong place.
    if yaml.safe_load(block) != {"serviceContract": umbrella_values["serviceContract"]}:
        sys.exit("the extracted serviceContract block does not parse to the umbrella's "
                 "serviceContract; the column-0 end rule cut it in the wrong place")

    values = (
        "# GENERATED by hack/gen-capabilities-chart.py from blueprints/openstack/chart/values.yaml.\n"
        "# Do not edit: change the umbrella's serviceContract and regenerate.\n"
        "#\n"
        "# The same serviceContract the umbrella takes. Pass this chart the same values file you\n"
        "# pass the Openstack Composition (its other keys are ignored here), so a deployer's\n"
        "# override of the capabilities applies to the objects this chart renders.\n"
        + block
    )

    schema_in = json.loads((umbrella / "values.schema.json").read_text())
    sc = schema_in["properties"]["serviceContract"]
    schema = {
        "$schema": schema_in.get("$schema", "http://json-schema.org/draft-07/schema"),
        "type": "object",
        "title": "OpenStack capabilities (per cluster)",
        "description": (
            "GENERATED by hack/gen-capabilities-chart.py from the umbrella's values.schema.json. "
            "The capability ClusterRoles and admission guards of the OpenStack blueprint, "
            "rendered from the same serviceContract the umbrella takes. Other top-level keys "
            "are accepted and ignored, so the umbrella's values file can be passed unchanged."
        ),
        "required": [
            "serviceContract",
        ],
        "properties": {
            "serviceContract": sc,
        },
        "definitions": referenced_definitions(sc, schema_in.get("definitions", {}), {}),
    }

    return {
        TPL: (umbrella / TPL).read_text(),
        "values.yaml": values,
        "values.schema.json": json.dumps(schema, indent=2) + "\n",
    }


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    root = Path(args[0] if args else ".")
    target = root / "blueprints" / "openstack" / "capabilities"
    if not (target / "Chart.yaml").is_file():
        sys.exit(f"no per-cluster chart at {target}")

    stale = []
    for rel, want in generate(root).items():
        path = target / rel
        have = path.read_text() if path.is_file() else None
        if have == want:
            continue
        stale.append(rel)
        if check:
            print(f"--- {path} differs from what the umbrella generates:")
            sys.stdout.writelines(difflib.unified_diff(
                (have or "").splitlines(keepends=True), want.splitlines(keepends=True),
                fromfile=f"{rel} (committed)", tofile=f"{rel} (generated)", n=2))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want)
            print(f"wrote {path}")

    if check and stale:
        print(f"\n{len(stale)} generated file(s) out of date: {', '.join(stale)}")
        print("Run: python3 hack/gen-capabilities-chart.py")
        return 1
    if check:
        print("per-cluster chart inputs match the umbrella")
    return 0


if __name__ == "__main__":
    sys.exit(main())
